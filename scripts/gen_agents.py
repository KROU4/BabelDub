"""Generate Claude Code subagents from the portable BabelDub role files.

Source:  skills/babeldub-localize/references/roles/<role>.md
         (frontmatter: name, description, tools, model; body: the role instructions)
Target:  claude/agents/babeldub-<role>.md
         (Claude Code subagent: frontmatter name, description, tools, model; body: a reminder of the
         babeldub-localize skill followed by the full role text)

Roles are the single source of truth: hosts without subagents (Codex, Gemini, web chats) read the
role files directly, Claude Code gets generated agents. Never edit claude/agents/ by hand.

Usage:
    python scripts/gen_agents.py            write/refresh claude/agents, drop stale generated files
    python scripts/gen_agents.py --check    CI: exit 1 if claude/agents differs from the roles
Options --roles DIR and --out DIR override the folders (used by tests).
Exit codes: 0 ok, 1 drift found by --check, 2 invalid role file or arguments.
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from dataclasses import dataclass
from pathlib import Path
from typing import Any

import yaml

ROOT = Path(__file__).resolve().parent.parent
ROLES_DIR = ROOT / "skills" / "babeldub-localize" / "references" / "roles"
AGENTS_DIR = ROOT / "claude" / "agents"
PLUGIN_JSON = ROOT / ".claude-plugin" / "plugin.json"

PREFIX = "babeldub-"
MARKER = "<!-- Generated by scripts/gen_agents.py"
NAME_RE = re.compile(r"^[a-z0-9]+(?:-[a-z0-9]+)*$")
FRONTMATTER_RE = re.compile(r"\A---[ \t]*\r?\n(?P<yaml>.*?)\r?\n---[ \t]*(?:\r?\n|\Z)", re.S)
# Optional Claude Code subagent fields copied through when a role sets them.
PASSTHROUGH = ("skills", "color", "effort", "maxTurns")
# Stage skill that holds the detailed rules for each role (shown in the reminder).
STAGE_SKILL = {
    "scout": "babeldub-recon",
    "caster": "babeldub-cast",
    "lexicon": "babeldub-translate",
    "translator": "babeldub-translate",
    "editor": "babeldub-translate",
    "voice": "babeldub-voice",
    "qa": "babeldub-qa",
    "packer": "babeldub-pack",
}


class RoleError(Exception):
    """A role file that cannot be turned into an agent."""


@dataclass
class Agent:
    role: str
    source: Path
    filename: str
    text: str


def _yaml_str(value: str) -> str:
    """A YAML double-quoted scalar (JSON string syntax is valid YAML)."""
    return json.dumps(value, ensure_ascii=False)


def _rel(path: Path) -> str:
    try:
        return path.resolve().relative_to(ROOT).as_posix()
    except ValueError:
        return path.as_posix()


def parse_role(path: Path) -> tuple[dict[str, Any], str]:
    raw = path.read_bytes()
    if raw.startswith(b"\xef\xbb\xbf"):
        raise RoleError(f"{path.name}: UTF-8 BOM is not allowed")
    text = raw.decode("utf-8")
    match = FRONTMATTER_RE.match(text)
    if not match:
        raise RoleError(f"{path.name}: no YAML frontmatter (--- ... ---) at the top")
    try:
        meta = yaml.safe_load(match.group("yaml")) or {}
    except yaml.YAMLError as exc:
        raise RoleError(f"{path.name}: invalid YAML frontmatter ({exc})") from exc
    if not isinstance(meta, dict):
        raise RoleError(f"{path.name}: frontmatter must be a mapping")
    return meta, text[match.end() :]


def _tools(value: Any, path: Path) -> str | None:
    if value is None:
        return None
    if isinstance(value, str):
        items = [t.strip() for t in value.split(",")]
    elif isinstance(value, list) and all(isinstance(t, str) for t in value):
        items = [t.strip() for t in value]
    else:
        raise RoleError(f"{path.name}: tools must be a comma-separated string or a list of strings")
    items = [t for t in items if t]
    if not items:
        raise RoleError(f"{path.name}: tools is empty (omit the field to inherit all tools)")
    return ", ".join(items)


def build_agent(path: Path) -> Agent:
    meta, body = parse_role(path)
    raw_name = str(meta.get("name") or path.stem).strip()
    role = raw_name[len(PREFIX) :] if raw_name.startswith(PREFIX) else raw_name
    if not NAME_RE.match(role):
        raise RoleError(f"{path.name}: role name '{raw_name}' must be lowercase letters, digits and hyphens")
    if role != path.stem and f"{PREFIX}{role}" != path.stem:
        raise RoleError(f"{path.name}: frontmatter name '{raw_name}' does not match the file name")
    description = meta.get("description")
    if not isinstance(description, str) or not description.strip():
        raise RoleError(f"{path.name}: description is required")
    model = str(meta.get("model") or "inherit").strip()
    tools = _tools(meta.get("tools"), path)

    lines = ["---", f"name: {PREFIX}{role}", f"description: {_yaml_str(' '.join(description.split()))}"]
    if tools:
        lines.append(f"tools: {_yaml_str(tools)}")
    lines.append(f"model: {model}")
    for key in PASSTHROUGH:
        if key in meta and meta[key] is not None:
            dumped = yaml.safe_dump(
                {key: meta[key]}, allow_unicode=True, default_flow_style=None, sort_keys=False
            )
            lines.append(dumped.strip())
    lines.append("---")

    source = _rel(path)
    stage_skill = STAGE_SKILL.get(role)
    reminder = [
        "",
        f"{MARKER} from {source}. Edit the role file, not this one. -->",
        "",
        "> You work inside the BabelDub pipeline. The procedure, stage order, exit codes and shared rules "
        "are in the `babeldub-localize` skill (`skills/babeldub-localize/SKILL.md`; commands are in "
        "`skills/babeldub-localize/references/pipeline.md`).",
    ]
    if stage_skill:
        reminder.append(f"> The detailed rules for your stage are in the `{stage_skill}` skill.")
    reminder += [
        "> Core principle: dub in the original hero's voice, with the same timbre, emotion and delivery, "
        "only in the target language.",
        "> Talk to the user in the user's language.",
        "",
    ]
    text = "\n".join(lines + reminder) + "\n" + body.strip("\r\n").replace("\r\n", "\n") + "\n"
    return Agent(role=role, source=path, filename=f"{PREFIX}{role}.md", text=text)


def collect(roles_dir: Path) -> list[Agent]:
    if not roles_dir.is_dir():
        raise RoleError(f"roles folder not found: {roles_dir}")
    paths = sorted(p for p in roles_dir.glob("*.md") if p.is_file())
    if not paths:
        raise RoleError(f"no role files (*.md) in {roles_dir}")
    agents = [build_agent(p) for p in paths]
    seen: dict[str, Path] = {}
    for agent in agents:
        if agent.filename in seen:
            raise RoleError(
                f"{agent.source.name} and {seen[agent.filename].name} both produce {agent.filename}"
            )
        seen[agent.filename] = agent.source
    return agents


def _is_generated(path: Path) -> bool:
    try:
        return MARKER in path.read_text(encoding="utf-8", errors="replace")
    except OSError:
        return False


def plan(agents: list[Agent], out_dir: Path) -> tuple[list[Agent], list[Path]]:
    """Agents whose file is missing or different, and stale generated files to remove."""
    changed = []
    for agent in agents:
        target = out_dir / agent.filename
        current = target.read_bytes().decode("utf-8", errors="replace") if target.exists() else None
        if current != agent.text:
            changed.append(agent)
    expected = {a.filename for a in agents}
    stale = (
        [p for p in sorted(out_dir.glob(f"{PREFIX}*.md")) if p.name not in expected and _is_generated(p)]
        if out_dir.is_dir()
        else []
    )
    return changed, stale


def plugin_agents_problem(agents: list[Agent], out_dir: Path, plugin_json: Path) -> str | None:
    """The plugin manifest must list every generated agent (Claude Code takes files, not a folder)."""
    if not plugin_json.exists():
        return None
    try:
        listed = json.loads(plugin_json.read_text(encoding="utf-8")).get("agents", [])
    except (OSError, ValueError, AttributeError):
        return f"{_rel(plugin_json)}: cannot read the agents list"
    try:
        rel_dir = out_dir.resolve().relative_to(plugin_json.resolve().parent.parent).as_posix()
    except ValueError:
        return None
    expected = sorted(f"./{rel_dir}/{a.filename}" for a in agents)
    listed = sorted(listed) if isinstance(listed, list) else []
    missing = [p for p in expected if p not in listed]
    if missing:
        return f'{_rel(plugin_json)}: add to "agents": {", ".join(missing)}'
    return None


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Generate claude/agents/*.md from BabelDub role files.")
    parser.add_argument("--check", action="store_true", help="only compare, exit 1 on drift (CI)")
    parser.add_argument("--roles", type=Path, default=ROLES_DIR, help="folder with role files")
    parser.add_argument("--out", type=Path, default=AGENTS_DIR, help="folder for generated agents")
    parser.add_argument(
        "--plugin-json", type=Path, default=PLUGIN_JSON, help="manifest that lists the agents"
    )
    args = parser.parse_args(argv)
    for stream in (sys.stdout, sys.stderr):  # non-ASCII role text must not crash cp1252 CI consoles
        try:
            stream.reconfigure(encoding="utf-8", errors="replace")  # type: ignore[union-attr]
        except (AttributeError, ValueError, OSError):
            pass

    try:
        agents = collect(args.roles)
    except (RoleError, OSError, UnicodeDecodeError) as exc:
        print(f"gen_agents: role error: {exc}", file=sys.stderr)
        return 2
    changed, stale = plan(agents, args.out)
    manifest_problem = plugin_agents_problem(agents, args.out, args.plugin_json)

    if args.check:
        problems = [f"outdated or missing: {_rel(args.out / a.filename)}" for a in changed]
        problems += [f"stale generated file: {_rel(p)}" for p in stale]
        if manifest_problem:
            problems.append(manifest_problem)
        if problems:
            print("gen_agents --check: agents differ from the roles", file=sys.stderr)
            for line in problems:
                print(f"  - {line}", file=sys.stderr)
            print("Fix: python scripts/gen_agents.py", file=sys.stderr)
            return 1
        print(f"gen_agents --check: all {len(agents)} agents match their roles")
        return 0

    args.out.mkdir(parents=True, exist_ok=True)
    for agent in changed:
        (args.out / agent.filename).write_bytes(agent.text.encode("utf-8"))
    for path in stale:
        path.unlink()
    print(f"gen_agents: roles {len(agents)}, written {len(changed)}, stale removed {len(stale)}")
    if manifest_problem:
        print(f"gen_agents: warning: {manifest_problem}", file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main())
